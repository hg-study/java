package Ch14Reflection;

// =======================================
// 리플렉션 개념
// 실행 중에 클래스 정보를 얻고 조작하는 API
// =======================================

public class C00ReflectionInfo {

	// 리플렉션 ------
	// 리플렉션(Reflection) : 실행 중인 프로그램의 클래스, 인터페이스, 메서드, 필드 정보를 동적으로 얻고 조작하는 API
	// 컴파일할 때 알 수 없는 클래스의 정보도 얻고, 그 클래스의 메서드와 필드에 접근해 호출할 수 있음
	// 사용하는 패키지 : java.lang.reflect

	// 주요 클래스 ------
	// Class : 클래스의 메타데이터를 나타냄. 클래스 이름, 필드, 메서드, 생성자 정보를 얻음
	// Field : 필드를 나타냄. 이름, 자료형, 접근 제어자를 얻고 값을 읽거나 바꿈
	// Method : 메서드를 나타냄. 이름, 매개변수 타입, 반환형, 접근 제어자를 얻고 호출(invoke)함
	// Constructor : 생성자를 나타냄. 매개변수 타입을 얻고 호출해 객체를 만듦(newInstance)

	// 사용처 ------
	// 일반 개발에서는 자주 쓰지 않지만 프레임워크, 라이브러리, 테스트 도구처럼 동적인 환경이 필요한 곳에서 유용함
	// 성능 문제가 있으므로 가능하면 정적인 방법으로 코드를 작성하는 것이 좋음

}

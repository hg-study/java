package Ch17Stream;

// =======================================
// 스트림 개념
// 컬렉션을 처리하고 변환하는 자바 8 의 기능
// =======================================

public class C00StreamInfo {

	// 스트림 ------
	// 스트림(Stream) : 자바 8 에 도입된 기능으로 컬렉션의 데이터를 효율적으로 처리하고 변환하는 연산을 제공함
	// 구조 : 생성 -> 중개 연산(여러 번 연결 가능) -> 최종 연산(결과를 만들고 스트림 종료)
	// 지연 연산 : 중개 연산만으로는 실제 처리가 일어나지 않고 최종 연산이 호출될 때 한꺼번에 실행됨

	// 중개 연산 (Intermediate operations) ------
	// 요소를 변환하거나 필터링하며 결과가 스트림이라 파이프라인으로 여러 번 호출할 수 있음
	// filter : 조건에 맞는 요소를 선택함 (중요)
	// map : 요소를 다른 형태로 변환함 (중요)
	// flatMap : 각 요소를 변환하고 하나의 스트림으로 평면화함
	// distinct : 중복된 요소를 제거함
	// sorted : 요소를 정렬함
	// limit : 지정한 개수만큼만 남김
	// skip : 처음 몇 개의 요소를 건너뜀

	// 최종 연산 (Terminal operations) ------
	// 스트림을 소비해 결과를 만들며 한 번 호출하면 스트림을 다시 쓸 수 없음
	// forEach : 각 요소를 반복 처리함 (중요)
	// collect : 요소를 모아 새 컬렉션을 만듦 (중요)
	// reduce : 요소를 하나의 값으로 줄임 (중요)
	// min, max : 최소값, 최대값
	// count : 요소의 개수
	// anyMatch, allMatch, noneMatch : 하나 이상, 모두, 하나도 조건과 일치하지 않는지 검사
	// findFirst, findAny : 첫 번째 요소, 임의의 요소

}

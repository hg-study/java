package Ch19Annotation;

// =======================================
// 어노테이션 개념
// 표준, 메타, 사용자 정의 어노테이션
// =======================================

public class C00AnnotationInfo {

	// 어노테이션 ------
	// 어노테이션(Annotation, @) : 다른 프로그램에게 유용한 정보를 제공하는 표시. 주석처럼 보이지만 컴파일러와 실행 환경이 읽어 동작에 쓸 수 있음
	// 역할 1 : 컴파일러에게 문법 에러를 체크하도록 정보를 제공함
	// 역할 2 : 빌드할 때 코드를 자동으로 생성하도록 정보를 제공함
	// 역할 3 : 실행 중에 특정 기능을 수행하도록 정보를 제공함 (리플렉션으로 읽음)
	// 해당 대상에 대한 동작을 수행하는 프로그램 외에는 다른 프로그램에 영향을 주지 않음
	// 참고 : https://ittrue.tistory.com/156

	// 표준 어노테이션 : 자바가 기본으로 제공 ------
	// @Override : 메서드를 오버라이딩한다고 컴파일러에게 알림
	// @Deprecated : 앞으로 사용하지 않을 대상임을 알림
	// @FunctionalInterface : 함수형 인터페이스임을 알림
	// @SuppressWarnings : 컴파일러가 경고 메시지를 내지 않게 함
	// @SafeVarargs : 제네릭 가변 인자를 사용할 때의 경고를 내지 않게 함

	// 메타 어노테이션 : 어노테이션을 정의할 때 붙이는 어노테이션 ------
	// @Target : 어노테이션을 적용할 대상(클래스, 필드, 메서드 등)을 지정함
	// @Retention : 어노테이션이 유지되는 기간(소스, 클래스, 실행 중)을 정함
	// @Documented : 어노테이션 정보를 javadoc 문서에 포함시킴
	// @Inherited : 어노테이션이 하위 클래스에 상속되게 함
	// @Repeatable : 어노테이션을 반복해서 적용할 수 있게 함

	// 사용자 정의 어노테이션 ------
	// 사용자가 @interface 로 직접 정의해 사용하는 어노테이션

}

package Ch15DesignPattern;

// =======================================
// 디자인 패턴 개념
// 자주 쓰는 설계 문제의 해결 방식을 이름 붙여 정리한 것
// =======================================

public class C00DesignPatternInfo {

	// 디자인 패턴 ------
	// 디자인 패턴 : 소프트웨어를 설계할 때 반복해서 나타나는 문제에 대한 검증된 해결 방식. 생성, 구조, 행위 세 종류로 나눔

	// 생성 패턴 (creational) : 객체를 만드는 방식에 관한 패턴 ------
	// 싱글톤(Singleton) : 인스턴스를 하나만 만들어 어디서든 같은 객체를 쓰게 보장함
	// 빌더(Builder) : 복잡한 객체를 단계별로 조립해 만듦. 생성 과정을 사용자에게 드러내지 않음
	// 프로토타입(Prototype) : 기존 객체를 복제해 새 객체를 만듦. 초기화가 복잡한 객체에 유용함
	// 팩토리 메서드(Factory Method) : 객체 생성을 서브 클래스에 맡김. 슈퍼 클래스는 생성용 추상 메서드만 정의함
	// 추상 팩토리(Abstract Factory) : 서로 관련된 객체의 세트를 만드는 인터페이스를 제공함

	// 구조 패턴 (structural) : 클래스와 객체를 조합하는 방식에 관한 패턴 ------
	// 어댑터(Adapter) : 호환되지 않는 인터페이스를 변환해 함께 동작하게 함
	// 데코레이터(Decorator) : 기존 객체를 감싸 기능을 동적으로 추가함
	// 프록시(Proxy) : 실제 객체 대신 대리인을 두어 접근을 제어함

	// 행위 패턴 (behavioral) : 객체 사이의 역할과 동작에 관한 패턴 ------
	// 옵저버(Observer) : 한 객체의 상태 변화를 관찰하는 다른 객체들에게 자동으로 알림
	// 전략(Strategy) : 알고리즘을 캡슐화해 실행 중에 교체함
	// 커맨드(Command) : 요청을 객체로 만들어 전달하고 저장하고 실행함

}

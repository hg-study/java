package Ch01Variable;

// =======================================
// 음수 표현과 보수
// 1의 보수, 2의 보수, 부호 비트와 보수를 이용한 뺄셈
// =======================================

public class C03Negative {
    public static void main(String[] args) {

        // 보수와 음수 ------
        /*
            OX 문제
            컴퓨터(CPU)는 구조상 덧셈 연산을 할 수 있다.(O)
            컴퓨터(CPU)는 구조상 뺄셈 연산을 할 수 있다.(X)
            보수 개념과 가산 처리를 통해 뺄셈 결과를 만들어낸다.

            설명 : CPU 안의 ALU(산술논리연산장치)에는 가산기(Adder, 더하기 수행 회로)만 들어있다. 그래서 뺄셈을 직접 수행하지 않고, 보수(Complement)를 사용해 뺄셈을 덧셈으로 바꾸어 처리한다.

            보수 : 보충해주는 수. 작은 수 A를 큰 수 B로 만들기 위해 채워야 하는 차액
            1의 보수 : 모든 비트를 반전시킨 것 (0 -> 1, 1 -> 0)
            2의 보수 : 1의 보수에 1을 더한 것. 음수 -B는 B의 2의 보수로 표현함

            부호 비트 : 숫자 맨 앞 비트. 0이면 양수(+), 1이면 음수(-)

            7 - 4 = 3
            7 + 6 = 3
            77 - 32 = 45
            77 + 68 = 45

            5 - 5 = 0
            5 + 5 = 0

              00000101 = 5
              11111010 = 5에 대한 1의 보수(-6)
              11111011 = 5에 대한 2의 보수(-5)

              00000101 = 5
            + 11111011 = 5에 대한 2의 보수(-5)
            -----------------------------
            (1)00000000 = 0   <- 넘치는 1은 버린다

            11111010 = -128 + 64 + 32 + 16 + 8 + 2 = -6
        */

        // 문제 ------
        // 음수 값임을 고려해 10진수는 8비트 2진수로, 8비트 2진수는 10진수로 바꾸는 문제
        /*
            10진수 -> 2진수
            111     -> 01101111
            -111    -> 10010001   (01101111 반전 10010000 + 1)
            96      -> 01100000
            -96     -> 10100000   (01100000 반전 10011111 + 1)
            31      -> 00011111
            -31     -> 11100001   (00011111 반전 11100000 + 1)

            2진수     -> 10진수
            10101111  -> -128+32+8+4+2+1 = -81
            00110101  -> 32+16+4+1 = 53
            11001100  -> -128+64+8+4 = -52
            10101010  -> -128+32+8+2 = -86
        */

		/*
		답
		10 진수 -> 2진수
        111     ->  01101111
        -111    ->  10010001
        96      ->  01100000
        -96     ->  10100000
        31      ->  00011111
        -31     ->  11100001

		2진수        -> 10진수
        10101111    ->  -81
        00110101    ->  53
        11001100    ->  -52
        10101010    ->  -86
        */

        // 풀이 확인 ------
        // 위 문제의 풀이를 코드로 확인하는 부분

        // 10진수 -> 2진수 (8비트)
        int[] decimals = {111, -111, 96, -96, 31, -31};
        for (int d : decimals) {
            String bin = String.format("%8s", Integer.toBinaryString(d & 0xFF)).replace(' ', '0');
                // d & 0xFF : 음수의 32비트에서 하위 8비트만 남기는 비트 연산
                // String.format("%8s", ...) : 8칸 폭으로 맞추고 남는 앞자리는 공백으로 채움. replace로 공백을 0으로 바꿈
            System.out.printf("%d -> %s%n", d, bin);
        }

        // 2진수 -> 10진수 (부호 있는 8비트)
        String[] binaries = {"10101111", "00110101", "11001100", "10101010"};
        for (String b : binaries) {
            System.out.printf("%s -> %d%n", b, (byte) Integer.parseInt(b, 2));
                // Integer.parseInt(문자열, 2) : 2진수 문자열을 정수로 바꾸는 메서드
                // (byte) : 하위 8비트를 부호 있는 byte로 해석해 맨 앞 비트가 1이면 음수가 됨
        }
    }

}

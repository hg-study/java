package Ch01Variable;

// =======================================
// 진수 표현과 변환
// 2진수, 8진수, 10진수, 16진수 표기와 가중치 계산, 접두사와 서식문자
// =======================================

public class C02Radix {
	public static void main(String[] args) {

		// 진수 ------
		// 2진수 : 0과 1만 사용해 수를 표현하며 2^n 단위(1, 2, 4, 8...)로 자릿수를 올림
		// 비트(Bit) : 2진수의 한 자리(0 또는 1)를 나타내는 정보의 최소 단위
		// 16진수(Hex) : 0~9 숫자와 A~F 알파벳 6개를 합쳐 16개 기호로 수를 표현함. 2진수 4자리를 한 자리로 줄여 쓸 수 있음
		// 7(111)은 3자리가 꽉 찼으므로 8에서 모두 올림되어 1000(4자리)이 됨

//		10진수		16진수      2진수
//		0			0           0
//		1			1           1
//		2			2           10
//		3			3           11
//		4			4           100
//		5			5           101
//		6			6           110
//		7			7           111
//		8			8           1000
//		9			9           1001
//      10          A           1010
//      11          B           1011
//      12          C           1100
//      13          D           1101
//      14          E           1110
//      15          F           1111
//      16          10          10000

		// 비트 수와 표현 범위 ------
		// n비트는 2^n개의 수(0 ~ 2^n - 1)를 표현함
//		------------------------------
//		1bit : 2^1 = 2(0~1)
//		2bit : 2^2 = 4(0~3)
//		3bit : 2^3 = 8(0~7)
//		4bit : 2^4 = 16(0~15)
//		5bit : 2^5 = 32(0~31)
//		6bit : 2^6 = 64(0~63)
//		7bit : 2^7 = 128(0~127)
//		8bit : 2^8 = 256(0~255)
//		9bit : 2^9 = 512(0~511)
//		10bit: 2^10 = 1024(0~1023)
//		--------------------------------

		// 2진수에서 10진수로 변환 ------
		// 자리마다 가중치(2^7 ~ 2^0)를 곱해 모두 더하는 가중치 계산
//		1	1	1	1	1	1	1	1
//		*	*	*	*	*	*	*	*
//		2^7	2^6	2^5	2^4	2^3	2^2	2^1	2^0
//		128	64	32	16	8	4	2	1

		// 2진수 -> 10진수
		// 10101100 = 128 + 32 + 8 + 4
		// 10011010 = 128 + 16 + 8 + 2
		// 01101001 = 64 + 32 + 8 + 1
		// 10010010 = 128 + 16 + 2

		// 10진수 -> 2진수
		// 192 -> 11000000
		// 224 -> 11100000
		// 252 -> 11111100
		// 12 -> 00001100
		// 15 -> 00001111

		// 문제 ------
		// 가중치 계산으로 2진수와 10진수를 서로 바꾸는 문제
		// 2진수 -> 10진수
		// 10101100 = 128+32+8+4
		// 10011010 = 128+16+8+2
		// 01101001 = 64+32+8+1
		// 10010010 = 128+16+2
		// 11001100 = 128+64+8+4
		// 00110101 = 32+16+4+1
		// 10100110 = 128+32+4+2

		// 10진수 -> 2진수
		// 192 -> 11000000
		// 158 -> 10011110
		// 224 -> 11100000
		// 252 -> 11111100
		// 88 -> 01011000
		// 179 -> 10110011
		// 12 -> 00001100
		// 15 -> 00001111

		// 서식문자와 접두사 ------
		// %d : 10진수 서식문자
		// %o : 8진수 서식문자
		// %x : 16진수 서식문자
		// 0b : 2진수 리터럴 접두사
		// 0 : 8진수 리터럴 접두사
		// 0x : 16진수 리터럴 접두사
		// 코드 정렬 : ctrl + shift + f

		// 10진수로 출력 ------
		// 서식문자 %d로 각 진수의 리터럴을 10진수로 출력함
		System.out.printf("10진수: %d\n", 0b00001111);
		System.out.printf("10진수: %d\n", 173);     // 10진수
		System.out.printf("10진수: %d\n", 0255);    // 8진수 리터럴. 173과 같은 수
		System.out.printf("10진수: %d\n", 0xAD);    // 16진수 리터럴. 173과 같은 수

		// 8진수로 출력 ------
		// 서식문자 %o로 같은 수를 8진수로 출력함
		System.out.println();
		System.out.printf("8진수: %o\n", 173);     // 10진수 리터럴
		System.out.printf("8진수: %o\n", 0255);    // 8진수 리터럴
		System.out.printf("8진수: %o\n", 0xAD);    // 16진수 리터럴

		// 16진수로 출력 ------
		// 서식문자 %x로 같은 수를 16진수로 출력함
		System.out.println();
		System.out.printf("16진수: %x\n", 173);     // 10진수 리터럴
		System.out.printf("16진수: %x\n", 0255);    // 8진수 리터럴
		System.out.printf("16진수: %x\n", 0xAD);    // 16진수 리터럴

	}
}

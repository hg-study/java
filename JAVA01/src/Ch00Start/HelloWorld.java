package Ch00Start; 				// 패키지명: 클래스들을 그룹화하여 관리하는 폴더


// =================================
// Java 기본 구조 및 진입점(main) 정의
// =================================

// Java 프로그램의 구조
// Java는 모든 코드가 class 내부에 존재해야 한다. 클래스 외부에는 package 선언과 import 문만이 올 수 있다.

// JVM(Java Virtual Machine)의 역할
// 작성된 .java 파일이 컴파일되어 .class 파일이 되면 JVM이 이를 읽어 실행한다. 이때 JVM은 클래스 내부 main 메서드를 찾아 프로그램을 시작한다.

// static과 메모리
// static 키워드가 붙은 메서드나 변수는 프로그램 실행 시 Method Area(Static Area)라는 메모리 공간에 바로 로드된다. 때문에 객체를 생성(new)하지 않고도 실행 가능하다.

public class HelloWorld {	// class 선언부: 객체지향 문법 적용영역

	// ============================
    // 메서드(Method, 함수)의 종류
    // ============================
	// 라이브러리 메서드		: JDK나 외부 라이브러리에서 미리 만들어져 제공되는 기능 (예: println)
	// 사용자정의 메서드		: 특정 로직을 처리하기 위해 개발자가 직접 만드는 함수
	// main 메서드			   : JVM이 프로그램을 시작할 때 최초 호출해 실행하는 메서드
	
	// ============================
    // 주요 키워드 정의
    // ============================
	// public: 접근 제어자. 누구나 접근 가능
	// static: 정적 키워드. 미리 만들어져 인스턴스(객체) 생성 없이 메모리에 로드되어 즉시 실행 가능 상태가 됨
	// void: 반환 타입(Return Type). 메서드 실행 후 돌려줄 값(Return Value)이 없음
	// main: 메서드의 이름. 
	// (String[] args): 매개변수(Parameter). 프로그램 실행 시 외부에서 전달하는 문자열(String) 인자값들(args)의 배열([])
	
	// --- 요약 ---
	// 접근 제한 없이 어디서든(public) 객체 생성 과정 없이(static) 바로 찾아서 실행할 수 있는, 
	// 결과값 반환 없는(void) 메인 진입점(main)이며, 
	// 필요한 정보(String[] args)를 담을 수 있는 공간
	
	public static void main(String[] args) {	// main 메서드 선언부: 절차지향 문법 적용영역
		// --- 콘솔 출력 실행 ---
        // System.out: 표준 출력 스트림 객체
        // println(): 전달된 인자값을 콘솔에 출력하고 줄 바꿈을 수행하는 라이브러리 메서드
		System.out.println("Hello World");	// 출력 및 로직 수행
	}
}


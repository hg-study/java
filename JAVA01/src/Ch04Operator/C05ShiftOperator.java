package Ch04Operator;

// =======================================
// 시프트 연산자
// <<, >> 비트 이동 연산
// =======================================

public class C05ShiftOperator {

	public static void main(String[] args) {

		// 시프트 연산자 ------
		// 시프트 연산자 : 2진수의 비트를 왼쪽(<<) 또는 오른쪽(>>)으로 밀어 이동하는 연산자
		// n << k : 왼쪽으로 k칸 밀면 n x 2^k 와 같음(오른쪽 빈칸은 0으로 채움)
		// n >> k : 오른쪽으로 k칸 밀면 n / 2^k 의 몫과 같음(밀려난 비트는 버림)
		int num1 = 15;		//00000000 00000000 00000000 00001111

		int num2 = 20;		//00000000 00000000 00000000 00010100
		int num3 = num2<<3; //00000000 00000000 00000000 10100000 = 160 (20 x 2^3)
		int num4 = num2>>3; //00000000 00000000 00000000 00000010 = 2   (20 / 2^3 의 몫)

		System.out.println("<<Shift 연산결과 :" + num3);
		System.out.println(">>Shift 연산결과 :" + num4);

	}

}

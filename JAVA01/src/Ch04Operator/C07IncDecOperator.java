package Ch04Operator;

// =======================================
// 증감 연산자
// 전위와 후위 증감 연산의 계산 순서
// =======================================

public class C07IncDecOperator {
	public static void main(String[] args) {

		// 증감 연산자 ------
		// 전위 연산자 ++a, --a : 먼저 값을 바꾼 뒤 그 값으로 식을 계산함
		// 후위 연산자 a++, a-- : 현재 값으로 식을 계산한 뒤 값을 바꿈
		int a=5, b=6, c=10, d;
		boolean e;

		// 첫 번째 식 ------
		// ++a 는 a를 6으로 올려 계산하고, b-- 는 6으로 계산한 뒤 b를 5로 줄임
		d= ++a * b--; // 6 * 6 = 36, a=6, b=5, c=10
		 System.out.printf("a = %d, b = %d, d = %d\n", a, b, d);

		// 두 번째 식 ------
		// a++ 는 6으로 계산한 뒤 a를 7로 올리고, ++c 는 11로 올려 계산하고, b-- 는 5로 계산한 뒤 b를 4로 줄임
		d= a++ + ++c - b--; // 6 + 11 - 5 = 12, a=7, b=4, c=11
		System.out.printf("a = %d, b = %d, c = %d, d = %d\n", a, b, c, d);

		// 세 번째 식 ------
		// 변수를 다시 정하고(a=1, b=0) 논리 연산자와 증감 연산자를 함께 계산함
		// 왼쪽 a++>0 은 1>0 이라 true, 이후 a는 2가 됨. || 의 왼쪽이 true라 오른쪽 식은 실행하지 않음
		a=1;
		b=0;
		e=(a++>0)||((b*d/c)>0);  // a=2, b=0, c=11, d=12, e=true
		System.out.printf("a = %d, b = %d, c = %d, d = %d ,e = %b\n", a, b, c, d , e);
	}
}

package Ch01Class;

// =======================================
// 객체와 클래스 개념
// 객체 지향, 클래스, 자바의 메모리 영역
// =======================================

public class C00ObjectInfo {

	// 객체 ------
	// 객체(Object) : 독립된 공간을 차지하는 존재 또는 사물
	// 속성(Attribute) : 객체마다 구별되는 데이터. 변수로 저장함
	// 기능(Function) : 객체가 수행하는 동작. 메서드(함수)로 처리함

	// 객체 지향 ------
	// 객체 지향 : 현실 객체의 정보 중 문제 해결에 필요한 일부만 추려(추상화) 메모리에 저장하는 문법 체계

	// 클래스 ------
	// 클래스 : 같은 종류의 객체를 만들기 위해 속성과 기능을 선언해 둔 자료형. 객체를 만들기 전에는 메모리를 차지하지 않음
	// 객체 생성 : new 로 클래스를 정의하는 순간 선언한 속성과 기능대로 공간이 생김

	// 자바의 메모리 영역 ------
	// 스택 영역 : {} 안에서 만들어지고 사라지는 변수(int, double 등)와 참조변수
	// 클래스(메서드) 영역 : 생성자, 일반 메서드, static 메서드, static 변수
	// 힙 영역 : new 로 만든 객체가 저장되는 영역

	// 객체 생성 과정 ------
	// Scanner sc = new Scanner(System.in);
	// new : 힙 영역에 객체를 저장함
	// Scanner(System.in) : 생성자를 호출해 객체 생성에 필요한 초기값을 부여함
	// Scanner sc : 스택에 만든 참조변수. 힙에 만들어진 객체의 시작 주소값을 저장함

}

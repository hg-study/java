package Ch05Inheritance;

// =======================================
// 업캐스팅과 다운캐스팅
// 클래스 참조변수의 형변환
// =======================================

class C06Super{
    int n1;
}

class C06Sub extends C06Super{
    int n2;
}

public class C06UpDownCasting {
    public static void main(String[] args) {

        // 캐스팅 ------
        // 캐스팅(Casting) : 자료형을 바꾸는 형변환
        // 클래스 캐스팅은 상속 관계에서 업캐스팅과 다운캐스팅 두 가지가 있음

        // 형변환 없음
        C06Super ob1 = new C06Super();
        ob1.n1 = 10;

        C06Sub ob2 = new C06Sub();
        ob1.n1 = 11;
        ob2.n2 = 20;

        // 업캐스팅 ------
        // 업캐스팅(Upcasting) : 상위 클래스형 참조변수에 하위 클래스형 객체를 연결하는 것(중요)
        // 자동 형변환 : 하위 객체는 상위 멤버를 모두 가지고 있어 메모리 영역을 침범할 우려가 없음
        // 사용 이유 1) 상속 관계의 모든 하위 객체를 하나의 상위형 변수로 연결할 수 있음
        // 사용 이유 2) 업캐스팅된 상태에서도 재정의된 메서드에는 접근할 수 있음
        // 제한 : 상위형 변수로는 하위 클래스에 추가된 멤버(n2)에 접근할 수 없음
        C06Super ob3 = new C06Sub();    // 업캐스팅
        ob3.n1 = 10;
        // ob3.n2 = 20;    // 접근 불가

        C06Super ob4 = ob2;             // 업캐스팅
        ob4.n1 = 100;
        // ob4.n2 = 200;   // 접근 불가

        // 다운캐스팅 ------
        // 다운캐스팅(Downcasting) : 하위 클래스형 참조변수에 상위 클래스형 변수를 (하위형)으로 강제 변환해 넣는 것
        // 강제 형변환 : 업캐스팅한 객체를 되돌리는 경우에만 안전함. 처음부터 상위 객체였다면 실행 중 오류가 남
        // Sub ob5 = (Sub) new Super();    // 컴파일은 되지만 실행하면 ClassCastException

        C06Sub down = (C06Sub) ob4;     // ob4 는 실제로 Sub 객체이므로 안전함
        down.n1 = 100;
        down.n2 = 200;                  // 다운캐스팅 후에는 추가된 멤버에 접근 가능

    }
}
